import { readFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const schema = new URL("../../api/openapi/openapi.yaml", import.meta.url);
const generated = new URL("../src/shared/api/generated/openapi.ts", import.meta.url);
const banner = "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";
const expected = banner + astToString(await openapiTS(schema));
const actual = await readFile(generated, "utf8");

if (actual !== expected) {
  console.error("Generated OpenAPI types are stale. Run `npm run api:types` and commit the result.");
  process.exitCode = 1;
}
